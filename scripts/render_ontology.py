"""Render the ontology as a human-readable document, docs/ontology.md (for review).

Usage:
    uv run python -m scripts.render_ontology           # write docs/ontology.md
    uv run python -m scripts.render_ontology --check   # fail if the file is out of date

The YAML (src/legacybridge/semantic/ontology.yaml) is the source of truth; this file is derived.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from legacybridge.semantic.loader import Ontology, Rule, load_ontology

OUT = Path(__file__).resolve().parents[1] / "docs" / "ontology.md"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _sql(statements: list[str]) -> list[str]:
    return [line for s in statements for line in ("```sql", s.strip(), "```", "")]


def _rule(rule: Rule) -> list[str]:
    lines = [
        f"- **Check:** `{rule.check}` ({rule.kind}, severity `{rule.severity}`)",
        f"- **Message:** {rule.message}",
        f"- **Fix:** {rule.fix}",
        "",
    ]
    if rule.bad_sql:
        lines += ["Violates the rule:", "", *_sql(rule.bad_sql)]
    if rule.good_sql:
        lines += ["Complies:", "", *_sql(rule.good_sql)]
    for label, cells in (("Flagged values", rule.bad_cells), ("Clean values", rule.good_cells)):
        if cells:
            lines += [f"{label}:", ""]
            lines += [f"- `{c['column']}`: {c['value']}" for c in cells] + [""]
    return lines


def render(o: Ontology) -> str:
    out = [
        "# Ontology",
        "",
        "> Generated by `scripts/render_ontology.py` from"
        " `src/legacybridge/semantic/ontology.yaml`."
        " Do not edit by hand: change the YAML and regenerate.",
        ">",
        "> **For review.** This is the domain knowledge the agent relies on. Check that each"
        " definition says what your business means, that each metric computes what the name"
        " promises, and that each rule's fix is the right one. The inventory (`SIC-xx`) part"
        " describes a **synthetic stand-in** schema, not the real sicpt.",
        "",
        f"{len(o.terms)} terms, {len(o.entities)} entities, {len(o.joins)} joins, "
        f"{len(o.metrics)} metrics, {len(o.defects)} defect rules, {len(o.lints)} lint.",
        "",
        "## Glossary",
        "",
        "| Term | Synonyms | Definition | Defects |",
        "|---|---|---|---|",
    ]
    for t in o.terms:
        needs = " (needs a period)" if t.requires_period else ""
        out.append(
            f"| {t.name}{needs} | {_cell(', '.join(t.aliases))} | {_cell(t.definition)} | "
            f"{', '.join(t.defects)} |"
        )

    out += ["", "## Entities", ""]
    for e in o.entities:
        out += [
            f"### {e.name}",
            "",
            f"{e.description} Synonyms: {', '.join(e.aliases) or '-'}.",
            "",
            f"- Tables: {', '.join(f'`{t}`' for t in e.tables)}",
            f"- Key: {', '.join(f'`{k}`' for k in e.key)}",
            f"- Defects: {', '.join(e.defects) or '-'}",
            "",
            "| Role | Column |",
            "|---|---|",
            *[f"| {role} | `{col}` |" for role, col in e.columns.items()],
            "",
        ]

    out += ["## Joins", "", "| Name | From | To | Condition | Cardinality | Type | Defects |",
            "|---|---|---|---|---|---|---|"]  # fmt: skip
    for j in o.joins:
        out.append(
            f"| {j.name} | `{j.left.table}` | `{j.right.table}` | `{_cell(j.condition)}` | "
            f"{j.cardinality} | {j.join_type} | {', '.join(j.defects) or '-'} |"
        )
    out += [""] + [f"- **{j.name}:** {j.description}" for j in o.joins] + [""]

    out += ["## Metrics", ""]
    for m in o.metrics:
        params = ", ".join(f"`{k}` ({p.min}-{p.max})" for k, p in m.params.items()) or "none"
        out += [
            f"### {m.name}",
            "",
            f"{m.description}",
            "",
            f"- Synonyms: {', '.join(m.aliases) or '-'}",
            f"- Parameters: {params}",
            f"- Defects handled: {', '.join(m.defects) or '-'}",
            "",
            *_sql([o.expand(m.sql)]),
        ]

    out += ["## Defect rules", ""]
    for d in o.defects:
        out += [
            f"### {d.id} — {d.title}",
            "",
            f"Columns: {', '.join(f'`{c}`' for c in d.columns)}",
            "",
        ]
        out += _rule(d.rule)

    out += ["## Lints", ""]
    for lint in o.lints:
        out += [f"### {lint.id} — {lint.title}", ""] + _rule(lint.rule)
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/ontology.md is stale")
    args = parser.parse_args()
    text = render(load_ontology())
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/ontology.md is out of date: run `uv run python -m scripts.render_ontology`")
            return 1
        print("docs/ontology.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parents[1])} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
